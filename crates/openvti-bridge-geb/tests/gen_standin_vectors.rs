//! The generator for the committed STAND-IN vectors (`tests/fixtures/geb-path-b-vectors.json`
//! and `geb-path-b-vectors-2.json`).
//!
//! Geb's real vector files are not redistributed with this repository (see
//! `common/mod.rs`). The stand-ins have the same JSON shape and are read by the same test
//! code, but every key, nonce and value in them is ours: fresh throwaway keys derived from
//! SHA-256 of a label (so the output is reproducible), and every expected output computed
//! by THIS crate. They therefore prove self-consistency and that the fixture structure is
//! what `vectors.rs` / `vectors2.rs` expect. They do NOT prove agreement with Geb: the
//! real interop check is the same tests run against Geb's own files.
//!
//! - `committed_standins_are_what_the_generator_makes` (always runs) fails if a committed
//!   stand-in has drifted from what this generator produces, so the files cannot be hand-edited.
//! - To regenerate after a deliberate change:
//!   `cargo test -p openvti-bridge-geb --test gen_standin_vectors -- --ignored regenerate`
//!   and commit the two files.
#![allow(clippy::unwrap_used, clippy::expect_used)]

