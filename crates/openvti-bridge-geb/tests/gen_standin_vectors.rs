const TAG: &str = "openvti-bridges geb stand-in vectors v1";
const WARNING: &str = "STAND-IN VECTORS. Generated by openvti-bridge-geb's own code from fresh \
throwaway keys (tests/gen_standin_vectors.rs); not Geb's output. They prove self-consistency and \
fixture structure only, not agreement with Geb. Geb's real files, when present locally, replace them.";

/// 32 bytes derived from a label (and a retry counter): the only source of "randomness" here.
fn d(label: &str, n: u32) -> [u8; 32] {
    Sha256::digest(format!("{TAG}|{label}|{n}")).into()
}

fn d12(label: &str) -> [u8; 12] {
    d(label, 0)[..12].try_into().unwrap()
}

struct Id {
    label: &'static str,
    ed_seed: [u8; 32],
    x_secret: [u8; 32],
    ed_pub: [u8; 32],
    x_pub: [u8; 32],
    did: String,
}

impl Id {
    fn new(label: &'static str, n: u32) -> Self {
        let ed_seed = d(&format!("{label}/ed25519"), n);
        let x_secret = d(&format!("{label}/x25519"), n);
        let ed_pub = SigningKey::from_bytes(&ed_seed).verifying_key().to_bytes();
        let x_pub = rendezvous::e_public(&x_secret);
        let did = did_peer::encode(&ed_pub, &x_pub, None).unwrap();
        Self {
            label,
            ed_seed,
            x_secret,
            ed_pub,
            x_pub,
            did,
        }
    }
    fn key(&self) -> SigningKey {
        SigningKey::from_bytes(&self.ed_seed)
    }
    fn json(&self) -> Value {
        json!({
            "label": self.label,
            "ed25519_seed_hex": hex::encode(self.ed_seed),
            "ed25519_pub_hex": hex::encode(self.ed_pub),
            "x25519_secret_hex": hex::encode(self.x_secret),
            "x25519_pub_hex": hex::encode(self.x_pub),
            "did": self.did,
        })
    }
}

/// Alice, Bob and Alice's second device. Alice's DID must sort below Bob's (the ratchet vector
/// has her send on `lo2hi`), so the derivation retries with a counter until it does.
fn identities() -> (Id, Id, Id) {
    for n in 0.. {
        let (a, b) = (Id::new("alice", n), Id::new("bob", n));
        if a.did < b.did {
            return (a, b, Id::new("alice2", n));
        }
    }
    unreachable!()
}

fn pretty(v: &Value) -> String {
    format!("{}\n", serde_json::to_string_pretty(v).unwrap())
}

pub fn build_v1() -> Value {
    let (alice, bob, _) = identities();
    let hex32 = |b: &[u8]| hex::encode(b);

    // did_peer_2
    let did_peer_2 = json!({
        "what": "STAND-IN: did:peer:2 identities and alice's DID document, from did_peer::encode and ::document",
        "identities": [alice.json(), bob.json()],
        "did_document_alice": did_peer::document(&alice.did).unwrap(),
    });

    // inbox_derivation
    let inbox_derivation = json!({
        "what": "STAND-IN: bob's inbox keys, from inbox::inbox_secret / inbox_pubkey",
        "input": {"did": bob.did, "ikm_x25519_pub_hex": hex::encode(bob.x_pub)},
        "output": {
            "nostrSecret": hex32(&inbox::inbox_secret(&bob.x_pub).unwrap()),
            "nostrPubkey": hex32(&inbox::inbox_pubkey(&bob.x_pub).unwrap()),
            "inbox_pubkey_of": hex32(&inbox::inbox_pubkey(&bob.x_pub).unwrap()),
        }
    });

    // sealed_box
    let plaintext = r#"{"v":1,"from":"test"}"#;
    let content = sealed::seal_with(
        &bob.x_pub,
        &d("sealed/eph", 0),
        &d12("sealed/nonce"),
        plaintext.as_bytes(),
    )
    .unwrap();
    let raw = b64_decode(&content).unwrap();
    let sealed_box = json!({
        "what": "STAND-IN: a sealed box to bob, from sealed::seal_with with a labelled ephemeral key and nonce",
        "input": {
            "recipient_did": bob.did,
            "recipient_x25519_secret_hex": hex::encode(bob.x_secret),
            "recipient_x25519_pub_hex": hex::encode(bob.x_pub),
            "plaintext": plaintext,
        },
        "output": {
            "content_b64": content,
            "eph_pub_hex": hex32(&raw[..32]),
            "nonce_hex": hex32(&raw[32..44]),
            "ct_and_tag_len": raw.len() - 44,
        }
    });

    // pair_rendezvous
    let ka = rendezvous::pair_keys(&alice.x_secret, &bob.x_pub).unwrap();
    let kb = rendezvous::pair_keys(&bob.x_secret, &alice.x_pub).unwrap();
    assert_eq!(*ka.aead_key, *kb.aead_key);
    assert_eq!(*ka.nostr_secret, *kb.nostr_secret);
    let pair_pubkey = ka.pubkey_hex().unwrap();
    let pair_rendezvous = json!({
        "what": "STAND-IN: the alice/bob pair rendezvous keys, from rendezvous::pair_keys (both sides)",
        "input": {"alice_did": alice.did, "bob_did": bob.did},
        "output": {
            "aeadKey": hex32(&*ka.aead_key),
            "nostrPubkey": pair_pubkey,
            "nostrSecret": hex32(&*ka.nostr_secret),
            "same_both_sides": true,
        }
    });

    // mailbox_envelope
    let kind = 4177u32;
    let envelope = r#"{"t":"f","f":"AAAAAA==","d":"lo"}"#;
    let nonce = d12("mailbox/nonce");
    let content = pair::seal_with(&ka, kind, &nonce, envelope.as_bytes()).unwrap();
    let mailbox_envelope = json!({
        "what": "STAND-IN: a mailbox envelope on the pair key, from pair::seal_with with a labelled nonce",
        "input": {
            "aead_key_hex": hex32(&*ka.aead_key),
            "pair_pubkey_hex": pair_pubkey,
            "kind": kind,
            "aad_utf8": String::from_utf8(pair::aad(&pair_pubkey, kind)).unwrap(),
            "envelope_json": envelope,
        },
        "output": {"content_b64": content, "nonce_hex": hex::encode(nonce)}
    });

    // ratchet_frames: alice sends three frames on lo2hi; bob opens them 2, 0, 1.
    let side = ratchet::my_side(&alice.did, &bob.did).unwrap();
    assert_eq!(side, ratchet::Side::Lo);
    let ck = ratchet::channel_key(&ecdh(&alice.x_secret, &bob.x_pub).unwrap()).unwrap();
    let mut send = ratchet::SendChain::new(&ck, side).unwrap();
    let pts = [
        r#"{"k":"m","d":"zero","id":"0000000000000000"}"#,
        r#"{"k":"m","d":"one","id":"1111111111111111"}"#,
        r#"{"k":"m","d":"two","id":"2222222222222222"}"#,
    ];
    let mut frames = vec![];
    for (n, pt) in pts.iter().enumerate() {
        let f = b64_encode(
            &send
                .seal_with(&d12(&format!("ratchet/nonce/{n}")), pt.as_bytes())
                .unwrap(),
        );
        frames.push(json!({
            "counter": n,
            "frame_b64": f,
            "counter_hex": format!("{n:08x}"),
            "frame_id": frame_id::frame_id(&f),
        }));
    }
    let open_order: Vec<Value> = [2usize, 0, 1]
        .iter()
        .map(|&i| json!({"i": i, "plaintext": pts[i], "counters_after": [0, 3]}))
        .collect();
    let ratchet_frames = json!({
        "what": "STAND-IN: three dyad ratchet frames from ratchet::SendChain::seal_with with labelled nonces, opened out of order",
        "input": {
            "sender_did": alice.did,
            "receiver_did": bob.did,
            "sender_sends_on": "lo2hi",
            "sender_is_lower_did": true,
            "plaintexts": pts,
        },
        "output": {
            "frames": frames,
            "receiver_open_order": open_order,
            "second_open_of_frame_0": "unopened:replay n=0 recv=3",
        }
    });

    // sign_json
    let doc_text = r#"{"b":2,"a":"stand-in","n":{"z":false,"y":[3,1,2]}}"#;
    let doc: Value = serde_json::from_str(doc_text).unwrap();
    let sign_json = json!({
        "what": "STAND-IN: sign_json over a JSON string, from sign::sign_json (JCS + Ed25519)",
        "input": {
            "signer_did": alice.did,
            "signer_ed25519_seed_hex": hex::encode(alice.ed_seed),
            "json": doc_text,
        },
        "output": {
            "jcs_utf8": String::from_utf8(jcs(&doc)).unwrap(),
            "sig_b64url": sign::sign_json(&alice.key(), &doc).unwrap(),
            "verify_json": true,
        }
    });

    // leaf_binding
    let k = d("leaf/k", 0);
    let b = leaf::binding(&alice.key(), &alice.did, &k).unwrap();
    let lk = d("leaf/live-k", 0);
    let leaf_binding = json!({
        "what": "STAND-IN: the 0xF002 leaf binding for a labelled leaf key, from leaf::binding",
        "input": {
            "did": alice.did,
            "k_hex": hex::encode(k),
            "payload_json_as_passed": serde_json::to_string(&leaf::binding_doc(&alice.did, &k)).unwrap(),
        },
        "output": {
            "jcs_utf8_signed": String::from_utf8(leaf::signed_bytes(&alice.did, &k).unwrap()).unwrap(),
            "binding_string": b,
            "extension_0xF002_bytes_hex": hex::encode(leaf::extension_value(&b)),
            "leafVerdict": "bound",
        },
        "live_check": {
            "note": "STAND-IN: a second leaf key; the test re-derives its binding and checks it does not bind k",
            "k": hex::encode(lk),
            "leaf_binding_equals_string_given": true,
            "leafVerdict": "bound",
        }
    });

    // room_line
    let h = hex::encode(d("room", 0));
    let room = format!(
        "{}-{}-{}-{}-{}",
        &h[..8],
        &h[8..12],
        &h[12..16],
        &h[16..20],
        &h[20..32]
    );
    let line = LineBody::new(1_700_000_000_000, "hello stand-in room".into());
    let sdoc = signing_doc(&room, &alice.did, &line).unwrap();
    let sg = sign::sign_json(&alice.key(), &sdoc).unwrap();
    let mut signed = line.clone();
    signed.sg = Some(sg);
    let room_line = json!({
        "what": "STAND-IN: a signed room line and its derived id, from wire::signing_doc, sign::sign_json and line_id::line_id",
        "input": {"room": room, "author_did": alice.did, "at": line.at, "text": line.text},
        "output": {
            "plaintext_unsigned": serde_json::to_string(&RoomPlaintext::Line(line.clone())).unwrap(),
            "sig_payload_json_as_passed": serde_json::to_string(&sdoc).unwrap(),
            "sig_payload_jcs_utf8": String::from_utf8(jcs(&sdoc)).unwrap(),
            "plaintext_signed": serde_json::to_string(&RoomPlaintext::Line(signed)).unwrap(),
            "sigVerdict": "signed",
            "line_id": line_id::line_id(&room, &alice.did, line.at, &line.text).unwrap(),
        }
    });

    // frame_id
    let cases: Vec<Value> = ["", "AAAAAA==", "stand-in"]
        .iter()
        .map(|i| json!({"input": i, "frame_id": frame_id::frame_id(i)}))
        .collect();
    let frame_id_v = json!({
        "what": "STAND-IN: frame ids, from frame_id::frame_id",
        "cases": cases,
    });

    json!({
        "title": "Stand-in path B test vectors (generated by openvti-bridge-geb, not Geb's)",
        "generator": "crates/openvti-bridge-geb/tests/gen_standin_vectors.rs",
        "warning": WARNING,
        "vectors": {
            "did_peer_2": did_peer_2,
            "inbox_derivation": inbox_derivation,
            "sealed_box": sealed_box,
            "pair_rendezvous": pair_rendezvous,
            "mailbox_envelope": mailbox_envelope,
            "ratchet_frames": ratchet_frames,
            "sign_json": sign_json,
            "leaf_binding": leaf_binding,
            "room_line": room_line,
            "frame_id": frame_id_v,
        }
    })
}

pub fn build_v2() -> Value {
    let (alice, bob, alice2) = identities();

    // commit_hash: three commit byte strings; the lowest hash must not be the first one
    // (the test settles the last two and expects the same winner).
    let (commits, hashes, winner_index) = (0u32..)
        .find_map(|n| {
            let commits: Vec<Vec<u8>> = (0..3)
                .map(|i| {
                    let mut c = vec![0x00, 0x01, 0x00, 0x03];
                    c.extend_from_slice(&d(&format!("commit/{i}"), n)[..6 + 4 * i]);
                    c
                })
                .collect();
            let hashes: Vec<String> = commits
                .iter()
                .map(|c| hex::encode(commit_hash(c)))
                .collect();
            let w = (0..3).min_by_key(|&i| hashes[i].clone()).unwrap();
            (w >= 1).then_some((commits, hashes, w))
        })
        .unwrap();
    let inputs: Vec<Value> = commits
        .iter()
        .zip(&hashes)
        .map(|(c, h)| {
            let m = b64_encode(c);
            json!({
                "commit_bytes_hex": hex::encode(c),
                "envelope_m": m,
                "mc_envelope_json": serde_json::to_string(&json!({"t": "mc", "e": 0, "m": m})).unwrap(),
                "commitHash": h,
                "negative_sha256_of_m_utf8": hex::encode(Sha256::digest(m.as_bytes())),
            })
        })
        .collect();
    let winner = hashes[winner_index].clone();
    let commit_hash_v = json!({
        "what": "STAND-IN: commit hashes (SHA-256 of the decoded commit bytes) and the settle winner, from settle::commit_hash",
        "inputs": inputs,
        "settle_all": {"seen": hashes, "winner": winner, "winner_index": winner_index},
        "settle_with_mine": {"seen": &hashes[1..], "mine": winner, "winner": winner, "mineWon": true},
    });

    // exporter
    let room_id = "stand-in-room-01";
    let es = d("exporter/secret", 0);
    let labels = ["geb/room/v2/nostr", "geb/room/v2/aead"];
    let per: Value = labels
        .iter()
        .map(|l| {
            (
                l.to_string(),
                Value::String(hex::encode(mls_exporter(&es, l, room_id.as_bytes(), 32))),
            )
        })
        .collect::<serde_json::Map<_, _>>()
        .into();
    let nostr: [u8; 32] = mls_exporter(&es, labels[0], room_id.as_bytes(), 32)
        .try_into()
        .unwrap();
    let aead: [u8; 32] = mls_exporter(&es, labels[1], room_id.as_bytes(), 32)
        .try_into()
        .unwrap();
    let keys = rendezvous::RelayKeys::from_parts(nostr, aead);
    let exporter = json!({
        "what": "STAND-IN: MLS-Exporter outputs re-derived from a labelled exporter secret (RFC 9420 8.5, written in tests/common)",
        "input": {
            "room_id": room_id,
            "policy_json": r#"{"v":2,"committer":"any-staged","settleWindowMs":3000}"#,
            "founder_did": alice.did,
            "member_did": bob.did,
            "epoch": 1,
            "labels": labels,
            "context_utf8": room_id,
            "context_hex": hex::encode(room_id),
            "exporter_secret_hex": hex::encode(es),
        },
        "output": {
            "epoch_authenticator": hex::encode(d("exporter/epoch-authenticator", 0)),
            "founder": per,
            "member": per,
            "both_equal": true,
            "roomKeysV2": {
                "nostrSecret": hex::encode(nostr),
                "nostrPubkey": keys.pubkey_hex().unwrap(),
                "aeadKey": hex::encode(aead),
            },
        }
    });

    // signed_leaf
    let k_seed = d("signed-leaf/k-seed", 0);
    let k = SigningKey::from_bytes(&k_seed).verifying_key().to_bytes();
    let b = leaf::binding(&alice.key(), &alice.did, &k).unwrap();
    let signed = leaf::signed_bytes(&alice.did, &k).unwrap();
    let sig = base64_url_decode(&b);
    let signed_leaf = json!({
        "what": "STAND-IN: a signed leaf binding for a labelled leaf key, from leaf::binding",
        "input": {
            "did": alice.did,
            "did_ed25519_seed_hex": hex::encode(alice.ed_seed),
            "did_ed25519_pub_hex": hex::encode(alice.ed_pub),
            "k_seed_hex": hex::encode(k_seed),
            "k_hex": hex::encode(k),
            "payload_json_as_passed": serde_json::to_string(&leaf::binding_doc(&alice.did, &k)).unwrap(),
        },
        "output": {
            "jcs_utf8": String::from_utf8(signed.clone()).unwrap(),
            "jcs_hex": hex::encode(&signed),
            "binding_string": b,
            "signature_hex": hex::encode(sig),
            "extension_0xF002_bytes_hex": hex::encode(b.as_bytes()),
            "leafVerdict": "bound",
        }
    });

    // persona_card_v1: two same-person statements (one per device) and the card, signed by alice.
    let (link_at, card_at) = (1_700_086_400_000u64, 1_700_086_460_000u64);
    let stmt = |me: &Id, other: &Id| {
        let st =
            json!({"t": "same-person", "v": 1, "me": me.did, "other": other.did, "at": link_at});
        let sg = sign::sign_json(&me.key(), &st).unwrap();
        json!({"stmt": st, "sig": sg})
    };
    let card = json!({
        "t": "persona", "v": 1, "by": alice.did, "at": card_at,
        "links": [stmt(&alice, &alice2), stmt(&alice2, &alice)],
    });
    let persona = json!({
        "what": "STAND-IN: a persona card linking two devices, signed with sign::sign_json; verified by a test-only verifier",
        "input": {"by": alice.did, "other_device": alice2.did, "link_at": link_at, "card_at": card_at},
        "output": {
            "card": card,
            "sig": sign::sign_json(&alice.key(), &card).unwrap(),
            "card_payload_json_as_signed": serde_json::to_string(&card).unwrap(),
            "card_payload_jcs_hex": hex::encode(jcs(&card)),
            "room_line_plaintext_unsigned": serde_json::to_string(&json!({"t": "p", "at": card_at, "card": card})).unwrap(),
            "takeCard": {"taken": 2, "dropped": []},
            "personOf_by": [alice.did, alice2.did],
        }
    });

    // vrc: bob answers (response), alice completes.
    let (resp_iso, comp_iso) = ("2026-11-10T09:00:00Z", "2026-11-10T09:00:05Z");
    let issue = |iss: &Id, sub: &Id, iso: &str, label: &str| {
        let nonce = hex::encode(&d(label, 0)[..16]);
        let p = vrc::IssueParams {
            nonce,
            issuer_endpoint: iss.did.clone(),
            subject_endpoint: Some(sub.did.clone()),
            ieee7012_agreed: true,
        };
        vrc::issue(&iss.did, &iss.key(), &sub.did, iso_secs(iso), &p).unwrap()
    };
    let response = issue(&bob, &alice, resp_iso, "vrc/response-nonce");
    let completion = issue(&alice, &bob, comp_iso, "vrc/completion-nonce");
    let hash_data = |doc: &Value| {
        let mut unsecured = doc.clone();
        let proof = unsecured.as_object_mut().unwrap().remove("proof").unwrap();
        let mut config = proof;
        config.as_object_mut().unwrap().remove("proofValue");
        let mut hd = Sha256::digest(jcs(&config)).to_vec();
        hd.extend_from_slice(&Sha256::digest(jcs(&unsecured)));
        hex::encode(hd)
    };
    let vrc_v = json!({
        "what": "STAND-IN: two v2 VRCs from vrc::issue (response by bob about alice, completion by alice about bob) and their hashData",
        "input": {
            "invitation_json": serde_json::to_string(&json!({"type": "vrc-invitation", "did": alice.did})).unwrap(),
            "responder_created_iso": resp_iso,
            "inviter_created_iso": comp_iso,
            "issuer_seeds": {alice.did.clone(): hex::encode(alice.ed_seed), bob.did.clone(): hex::encode(bob.ed_seed)},
        },
        "output": {
            "response_vrc_by_bob_about_alice": response,
            "completion_vrc_by_alice_about_bob": completion,
            "hashData_hex": {"response": hash_data(&response), "completion": hash_data(&completion)},
        }
    });

    json!({
        "note": "STAND-IN, generated by tests/gen_standin_vectors.rs",
        "title": "Stand-in path B test vectors, round 2 (generated by openvti-bridge-geb, not Geb's)",
        "generator": "crates/openvti-bridge-geb/tests/gen_standin_vectors.rs",
        "warning": WARNING,
        "vectors": {
            "identities": [alice.json(), bob.json(), alice2.json()],
            "commit_hash": commit_hash_v,
            "exporter": exporter,
            "signed_leaf": signed_leaf,
            "persona_card_v1": persona,
            "vrc": vrc_v,
        }
    })
}

fn base64_url_decode(s: &str) -> Vec<u8> {
    use base64::Engine;
    base64::engine::general_purpose::URL_SAFE_NO_PAD
        .decode(s)
        .unwrap()
}

fn path(name: &str) -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures")
        .join(name)
}

#[test]
fn committed_standins_are_what_the_generator_makes() {
    for (name, built) in [(common::V1, build_v1()), (common::V2, build_v2())] {
        let text = std::fs::read_to_string(path(name)).unwrap();
        let committed: Value = serde_json::from_str(&text).unwrap();
        assert_eq!(
            committed, built,
            "{name} differs from the generator: regenerate with `cargo test -p openvti-bridge-geb --test gen_standin_vectors -- --ignored regenerate`"
        );
    }
}

#[test]
#[ignore = "writes tests/fixtures/*.json; run on purpose"]
fn regenerate_standin_vectors() {
    for (name, built) in [(common::V1, build_v1()), (common::V2, build_v2())] {
        std::fs::write(path(name), pretty(&built)).unwrap();
    }
}
